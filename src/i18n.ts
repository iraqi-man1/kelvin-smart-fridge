export const dictionaries: Record<Lang, Dict> = { ar, en, ms };
export const langs: [Lang, string][] = [['ar', 'ع'], ['en', 'EN'], ['ms', 'BM']];

const LANG_KEY = 'kelvin-lang';
const storedLang = (): Lang => {
  try { const l = localStorage.getItem(LANG_KEY); if (l === 'ar' || l === 'en' || l === 'ms') return l; } catch {}
  return 'ar';
};

export function useLangState() {
  const [lang, setLang] = useState<Lang>(storedLang);
  useEffect(() => {
    const root = document.documentElement;
    root.lang = lang; root.dir = dictionaries[lang].dir;
    try { localStorage.setItem(LANG_KEY, lang); } catch {}
  }, [lang]);
  return [lang, setLang] as const;
}

export const I18n = createContext<{ lang: Lang; t: Dict }>({ lang: 'ar', t: ar });
export const useT = () => useContext(I18n);
